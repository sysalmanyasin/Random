// One geometry for the PWA, the Capacitor Android app and the AuditWidget app. It is the DuaPharma family icon:
// the white pharmacy cross at a fixed position (shared with Dua BT Sales, Attendance, Closing, Mail, Inv Search)
// on this app's own crimson tile, with an amber barcode scan frame in the corner — scanning is this app's signature.
//
//   node scripts/build-brand.mjs          write SVG + Android XML outputs
//   node scripts/build-brand.mjs --check  change nothing, exit 1 if a generated text file is stale (used by tests)
//   node scripts/build-brand.mjs --png    also render every PNG (needs `npm i --no-save sharp`; not a dependency)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const BRAND = { crimson: '#8A2C3B', amber: '#F2B84B', white: '#FFFFFF' };
export const LABELS = { web: 'Dua Audit Hub', widget: 'Dua Audit Rounds' };

const n = (v) => String(+v.toFixed(2));
const rr = (x, y, w, h, r) =>
  `M${n(x + r)} ${n(y)}H${n(x + w - r)}A${r} ${r} 0 0 1 ${n(x + w)} ${n(y + r)}V${n(y + h - r)}A${r} ${r} 0 0 1 ${n(x + w - r)} ${n(y + h)}` +
  `H${n(x + r)}A${r} ${r} 0 0 1 ${n(x)} ${n(y + h - r)}V${n(y + r)}A${r} ${r} 0 0 1 ${n(x + r)} ${n(y)}Z`;

/** Cross (same coordinates as every other Dua app) + scan frame. 512-unit design space. */
export const PRIMS = [
  { d: rr(162, 84, 92, 240, 22), fill: BRAND.white },
  { d: rr(88, 158, 240, 92, 22), fill: BRAND.white },
  { d: 'M282 318V290Q282 282 290 282H318M392 282H420Q428 282 428 290V318M428 392V420Q428 428 420 428H392M318 428H290Q282 428 282 420V392', stroke: BRAND.amber, sw: 18 },
  { d: 'M300 355H410', stroke: BRAND.amber, sw: 14 },
];

const paint = (p, color) =>
  p.stroke
    ? `<path d="${p.d}" fill="none" stroke="${color ?? p.stroke}" stroke-width="${p.sw}" stroke-linecap="round" stroke-linejoin="round"/>`
    : `<path d="${p.d}" fill="${color ?? p.fill}"/>`;

/** kind: tile (rounded, any) | maskable | apple | foreground (transparent, adaptive safe zone) | mono | round */
export function svg(kind, title = LABELS.web) {
  const body = (color) => PRIMS.map((p) => paint(p, color)).join('');
  const head = (vb) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">\n  <title>${title}</title>\n`;
  switch (kind) {
    case 'tile': return `${head('0 0 512 512')}<rect width="512" height="512" rx="112" fill="${BRAND.crimson}"/>\n${body()}\n</svg>\n`;
    case 'maskable': return `${head('0 0 512 512')}<rect width="512" height="512" fill="${BRAND.crimson}"/>\n<g transform="translate(256 256) scale(0.72) translate(-255 -255)">${body()}</g>\n</svg>\n`;
    case 'apple': return `${head('0 0 512 512')}<rect width="512" height="512" fill="${BRAND.crimson}"/>\n<g transform="translate(256 256) scale(0.86) translate(-255 -255)">${body()}</g>\n</svg>\n`;
    case 'round': return `${head('0 0 512 512')}<circle cx="256" cy="256" r="256" fill="${BRAND.crimson}"/>\n<g transform="translate(256 256) scale(0.8) translate(-255 -255)">${body()}</g>\n</svg>\n`;
    case 'foreground': return `${head('0 0 108 108')}<g transform="translate(18.66 18.66) scale(0.1386)">${body()}</g>\n</svg>\n`;
    case 'mono': return `${head('0 0 512 512')}<g transform="translate(256 256) scale(0.72) translate(-255 -255)">${body('#000000')}</g>\n</svg>\n`;
    default: throw new Error(kind);
  }
}

// ── Android vector drawables ──
const vecPath = (p, white) => {
  const c = (x) => (white ? '#FFFFFF' : x);
  return p.stroke
    ? `        <path\n            android:strokeColor="${c(p.stroke)}"\n            android:strokeWidth="${p.sw}"\n            android:strokeLineCap="round"\n            android:strokeLineJoin="round"\n            android:pathData="${p.d}" />`
    : `        <path\n            android:fillColor="${c(p.fill)}"\n            android:pathData="${p.d}" />`;
};
const vecHead = '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n';
export const androidLayer = (white) =>
  `${vecHead}    <group\n        android:translateX="18.66"\n        android:translateY="18.66"\n        android:scaleX="0.1386"\n        android:scaleY="0.1386">\n${PRIMS.map((p) => vecPath(p, white)).join('\n')}\n    </group>\n</vector>\n`;
export const androidBackground = `${vecHead}    <path\n        android:fillColor="${BRAND.crimson}"\n        android:pathData="M0,0h108v108h-108z" />\n</vector>\n`;

const adaptive = (bg, fg) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Dua Audit Hub launcher icon (generated by scripts/build-brand.mjs — edit the generator, not this file). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="${bg}" />
    <foreground android:drawable="${fg}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

const CAP = 'AndroidApp/android/app/src/main/res';
const WID = 'AuditWidget/app/src/main/res';

/** Every generated text file. Pure, so the test can diff it against the repo. */
export function textOutputs() {
  const o = {};
  o['icons/icon.svg'] = svg('tile');
  o['icons/icon-maskable.svg'] = svg('maskable');
  o['icons/icon-monochrome.svg'] = svg('mono');
  // Capacitor app: adaptive background is a colour, foreground a density-specific PNG (written by --png).
  o[`${CAP}/mipmap-anydpi-v26/ic_launcher.xml`] = adaptive('@color/ic_launcher_background', '@mipmap/ic_launcher_foreground');
  o[`${CAP}/mipmap-anydpi-v26/ic_launcher_round.xml`] = adaptive('@color/ic_launcher_background', '@mipmap/ic_launcher_foreground');
  o[`${CAP}/drawable/ic_launcher_monochrome.xml`] = androidLayer(true);
  o[`${CAP}/values/ic_launcher_background.xml`] = `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${BRAND.crimson}</color>\n</resources>\n`;
  // Widget app: all-vector.
  o[`${WID}/drawable/ic_launcher_background.xml`] = androidBackground;
  o[`${WID}/drawable/ic_launcher_foreground.xml`] = androidLayer(false);
  o[`${WID}/drawable/ic_launcher_monochrome.xml`] = androidLayer(true);
  o[`${WID}/mipmap-anydpi-v26/ic_launcher.xml`] = adaptive('@drawable/ic_launcher_background', '@drawable/ic_launcher_foreground');
  o[`${WID}/mipmap-anydpi-v26/ic_launcher_round.xml`] = adaptive('@drawable/ic_launcher_background', '@drawable/ic_launcher_foreground');
  return o;
}

// ── PNG outputs ──
const DENS = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
export function pngPlan() {
  const p = [
    ['icons/icon-192.png', 'tile', 192], ['icons/icon-512.png', 'tile', 512],
    ['icons/icon-192-maskable.png', 'maskable', 192], ['icons/icon-512-maskable.png', 'maskable', 512],
    ['icons/icon-monochrome-512.png', 'mono', 512], ['icons/apple-touch-icon.png', 'apple', 180],
    ['favicon-16x16.png', 'tile', 16], ['favicon-32x32.png', 'tile', 32],
  ];
  for (const [d, k] of Object.entries(DENS)) {
    p.push([`${CAP}/mipmap-${d}/ic_launcher.png`, 'tile', Math.round(48 * k)]);
    p.push([`${CAP}/mipmap-${d}/ic_launcher_round.png`, 'round', Math.round(48 * k)]);
    p.push([`${CAP}/mipmap-${d}/ic_launcher_foreground.png`, 'foreground', Math.round(108 * k)]);
  }
  return p;
}

function ico(pngs) { // PNG-in-ICO, sizes < 256
  const head = Buffer.alloc(6); head.writeUInt16LE(1, 2); head.writeUInt16LE(pngs.length, 4);
  let off = 6 + 16 * pngs.length; const dir = []; 
  for (const { size, data } of pngs) {
    const e = Buffer.alloc(16); e[0] = size; e[1] = size; e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8); e.writeUInt32LE(off, 12); off += data.length; dir.push(e);
  }
  return Buffer.concat([head, ...dir, ...pngs.map((x) => x.data)]);
}

async function renderPngs() {
  let sharp;
  try { sharp = (await import('sharp')).default; } catch { console.error('PNG output needs sharp:  npm i --no-save sharp'); process.exit(2); }
  const png = (kind, size) => sharp(Buffer.from(svg(kind)), { density: 384 }).resize(size, size).png().toBuffer();
  for (const [rel, kind, size] of pngPlan()) {
    mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
    writeFileSync(join(ROOT, rel), await png(kind, size));
  }
  writeFileSync(join(ROOT, 'favicon.ico'), ico(await Promise.all([16, 32, 48].map(async (s) => ({ size: s, data: await png('tile', s) })))));
  const sheet = (bg, kind) => ''; void sheet;
}

async function main() {
  const check = process.argv.includes('--check');
  const drift = [];
  for (const [rel, content] of Object.entries(textOutputs())) {
    const abs = join(ROOT, rel);
    if (existsSync(abs) && readFileSync(abs, 'utf8') === content) continue;
    if (check) { drift.push(rel); continue; }
    mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, content); console.log('wrote', rel);
  }
  if (check) {
    if (drift.length) { console.error('Stale — run `node scripts/build-brand.mjs`:\n  ' + drift.join('\n  ')); process.exit(1); }
    console.log('brand outputs up to date'); return;
  }
  if (process.argv.includes('--png')) await renderPngs();
}
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
